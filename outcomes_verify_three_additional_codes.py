"""Independent original-XLSX and exact-rational check of three added endpoints.

This verifier does not import the production parser or statistical functions.
It validates input selections and denominators, extracts case (not mention)
counts by exact code, reconstructs the six disjoint adult strata, and compares
fixed pooled-weight risk estimates/intervals with the new aggregate CSV.
"""
from pathlib import Path
from fractions import Fraction as F
import argparse,csv,json,math,re
import openpyxl

ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--data-root',type=Path,required=True,help='Directory containing original acute denominator XLSX exports')
ap.add_argument('--production-csv',type=Path,required=True,help='Model-level CSV generated by outcomes_analyze_existing_binary.py')
ap.add_argument('--out-dir',type=Path,required=True,help='Directory for the public validation summary')
ap.add_argument('--private-audit',type=Path,help='Optional detailed local check log; do not publish')
args=ap.parse_args()
DATA=args.data_root.resolve();OUT=args.out_dir.resolve()
OUT.mkdir(parents=True,exist_ok=True)
CODES=['J96.00','U69.01','U69.04']; Z=1.959963984540054
ages={'age18_74':{'18-29 Jahre','30-39 Jahre','40-49 Jahre','50-54 Jahre','55-59 Jahre','60-64 Jahre','65-74 Jahre'},'age75plus':{'75-79 Jahre','80+ Jahre'}}
ops={a+'.'+b for a in ['8-981','8-98b'] for b in ['20','21','22','23','30','31','32','33']}
checks=[]
def ck(label,truth):
 checks.append({'check':label,'passed':bool(truth)})
 if not truth:raise AssertionError(label)
def norm(x):return str(x).strip().rstrip('!*')
source={}
for age,agevals in ages.items():
 for hd in ['allhd','i63','i61']:
  for kind in ['all','dys']:
   fn=DATA/f'acute_joint_{age}_{hd}_{kind}_2025.xlsx'
   with open(fn,'rb') as handle:
    wb=openpyxl.load_workbook(handle,read_only=True,data_only=True)
    info=list(wb['Info'].values);n=info[7][1]
    ck(fn.name+' integer N',type(n) in (int,float) and int(n)==n and n>0)
    ck(fn.name+' release',info[4][0]=='Unterjährige Datenlieferung DRG Januar bis Dezember 2025')
    fields={k.strip():{norm(v) for v in vals.split(',') if v.strip()} for k,vals in re.findall(r'([^();]+)\(([^()]*)\)',info[1][0])}
    allowed={'Prozeduren','Nebendiagnosen','Hauptdiagnose','Hauptdiagnosen','Altersklasse','Altersklassen','Altersgruppe','Entlassungsgrund'}
    ck(fn.name+' known fields',set(fields)<=allowed)
    ck(fn.name+' no discharge restriction',not fields.get('Entlassungsgrund'))
    ck(fn.name+' OPS',fields.get('Prozeduren')==ops)
    ck(fn.name+' exposure',fields.get('Nebendiagnosen',set())==({'R13.0','R13.1','R13.9'} if kind=='dys' else set()))
    agekeys=[k for k in fields if k.startswith('Alters')]
    hdkeys=[k for k in fields if k.startswith('Hauptdiagnos')]
    ck(fn.name+' age',len(agekeys)==1 and fields[agekeys[0]]==agevals)
    hdcodes=set() if hd=='allhd' else {hd.upper()+'.'+i for i in ['0','1','2','3','4','5','6','8','9']}
    ck(fn.name+' diagnosis',len(hdkeys)<=1 and (fields[hdkeys[0]] if hdkeys else set())==hdcodes)
    table=list(wb['Nebendiagnosen'].values)
    ck(fn.name+' case-column',table[0][2]=='Fälle' and table[0][3]=='Nennungen')
    event={}
    for code in CODES:
     found=[r for r in table[1:] if r[0] is not None and norm(r[0])==code]
     ck(fn.name+' '+code+' exactlyone',len(found)==1)
     v=found[0][2]
     ck(fn.name+' '+code+' integer bounds',type(v) in (int,float) and int(v)==v and 0<=v<=n)
     event[code]=int(v)
    source[age,hd,kind]={'n':int(n),**event}
    wb.close()
published={(r['outcome'],r['analysis']):r for r in csv.DictReader(args.production_csv.open(encoding='utf-8-sig'))}
for code in CODES:
 cells=[]
 for age in ages:
  for hd in ['i63','i61','other']:
   def val(kind,key):
    if hd!='other':return source[age,hd,kind][key]
    return source[age,'allhd',kind][key]-source[age,'i63',kind][key]-source[age,'i61',kind][key]
   nt,nd,et,ed=val('all','n'),val('dys','n'),val('all',code),val('dys',code)
   nc=nt-nd;ec=et-ed
   ck(code+age+hd+' denominator support',nd>0 and nc>0)
   ck(code+age+hd+' event bounds',0<=ed<=nd and 0<=ec<=nc)
   cells.append((nt,nd,nc,ed,ec))
 nt=sum(c[0] for c in cells)
 ck(code+' adult total',nt==279255)
 pd=pc=vd=vc=F(0)
 for n,d,c,e,f in cells:
  w=F(n,nt);p=F(e,d);q=F(f,c)
  pd+=w*p;pc+=w*q;vd+=w*w*p*(1-p)/d;vc+=w*w*q*(1-q)/c
 rr=float(pd/pc);rd=float(pd-pc);se=math.sqrt(float(vd/pd**2+vc/pc**2));sr=math.sqrt(float(vd+vc))
 expect={'all_n':nt,'dys_n':sum(c[1] for c in cells),'no_dys_n':sum(c[2] for c in cells),'dys_rate':float(pd),'no_dys_rate':float(pc),'rr':rr,'rr_ci_lower':rr*math.exp(-Z*se),'rr_ci_upper':rr*math.exp(Z*se),'risk_difference':rd,'risk_difference_ci_lower':rd-Z*sr,'risk_difference_ci_upper':rd+Z*sr}
 row=published[code,'age_principal_diagnosis']
 for k,v in expect.items():ck(code+' model '+k,abs(v-float(row[k]))<1e-10)
result={'status':'PASS','endpoints':CODES,'checks_passed':len(checks),'workbooks_read':12,'method':'Independent original-XLSX extraction, exact input-filter checking and exact-rational risk/variance reconstruction; no production parser or model functions imported.','checks':checks}
if args.private_audit:
 args.private_audit.parent.mkdir(parents=True,exist_ok=True)
 args.private_audit.write_text(json.dumps(result,indent=2),encoding='utf8')
public={k:v for k,v in result.items() if k!='checks'}
public['limitation']='Numerical verification does not establish causality, interval calibration, or admission-NIHSS adjustment; no sex/PCCL adjustment is available for these three codes.'
(OUT/'outcomes_three_additional_codes_validation_summary.json').write_text(json.dumps(public,indent=2),encoding='utf8')
print(json.dumps(public,indent=2))
